CREATE TABLE PATIENT_LAB_FILES (
    FILE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PATIENT_ID NUMBER NOT NULL,
    FILE_NAME VARCHAR2(255) NOT NULL,
    FILE_TYPE VARCHAR2(100) NOT NULL,
    FILE_SIZE VARCHAR2(50),
    FILE_DATA CLOB NOT NULL,
    UPLOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lab_patient FOREIGN KEY (PATIENT_ID) REFERENCES PATIENTS(PATIENT_ID) ON DELETE CASCADE
)
