);


-- ============================================
-- ROLES TABLE (Define available roles)
-- ============================================
CREATE TABLE roles (
    role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR2(50) NOT NULL UNIQUE,
    description VARCHAR2(255),
    permissions CLOB,  -- JSON array of permissions
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ============================================
-- PERMISSIONS TABLE (Fine-grained permissions)
-- ============================================
CREATE TABLE permissions (
    permission_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource VARCHAR2(100) NOT NULL,  -- e.g., 'appointments', 'patients', 'billing'
    action VARCHAR2(50) NOT NULL,     -- e.g., 'create', 'read', 'update', 'delete'
    description VARCHAR2(255),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT unique_permission UNIQUE (resource, action)
);

-- ============================================
-- ROLE_PERMISSIONS (Map roles to permissions)
-- ============================================
CREATE TABLE role_permissions (
    role_permission_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id NUMBER REFERENCES roles(role_id) ON DELETE CASCADE,
    permission_id NUMBER REFERENCES permissions(permission_id) ON DELETE CASCADE,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT unique_role_permission UNIQUE (role_id, permission_id)
);

-- ============================================
-- UPDATE USERS TABLE WITH ROLE
-- ============================================
ALTER TABLE users ADD (
    role_id NUMBER REFERENCES roles(role_id),
    status VARCHAR2(20) DEFAULT 'Active' NOT NULL,
    last_login TIMESTAMP,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);


