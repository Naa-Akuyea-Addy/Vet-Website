  category VARCHAR2(80),
  quantity NUMBER(10,2) DEFAULT 0 NOT NULL,
  reorder_level NUMBER(10,2) DEFAULT 0 NOT NULL,
  unit_cost NUMBER(12,2) DEFAULT 0 NOT NULL,
